/**
 * Generates:
 * - artifacts/web-app/src/data/wordList.ts (VALID_WORDS from tabatkins/wordle-list)
 * - artifacts/api-server/src/game/wordList.ts (ANSWER_WORDS = intersection with common solutions)
 */
import https from "node:https";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

function fetchText(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        if (res.statusCode && res.statusCode >= 400) {
          reject(new Error(`HTTP ${res.statusCode} for ${url}`));
          return;
        }
        let data = "";
        res.on("data", (c) => (data += c));
        res.on("end", () => resolve(data));
      })
      .on("error", reject);
  });
}

function parseFiveLetterWords(text) {
  return text
    .split(/\r?\n/)
    .map((w) => w.trim().toLowerCase())
    .filter((w) => /^[a-z]{5}$/.test(w));
}

function emitSetFile(name, wordsSorted) {
  const lines = wordsSorted.map((w) => `  ${JSON.stringify(w)},`);
  return `/** Auto-generated by scripts/generate-wordlists.mjs — do not edit by hand. */\nexport const ${name} = new Set<string>([\n${lines.join("\n")}\n]);\n`;
}

function emitApiWordList(validWordsSorted, answerWordsSorted) {
  const validLines = validWordsSorted.map((w) => `  ${JSON.stringify(w)},`);
  const answerLines = answerWordsSorted.map((w) => `  ${JSON.stringify(w)},`);
  return `/** Auto-generated by scripts/generate-wordlists.mjs — do not edit by hand. */
/** All valid guess words (tabatkins/wordle-list). */
export const VALID_WORDS = new Set<string>([
${validLines.join("\n")}
]);

/** Puzzle secret words only — common everyday solutions (~2.3k), subset of VALID_WORDS. */
export const ANSWER_WORDS: string[] = [
${answerLines.join("\n")}
];
`;
}

const tabatkinsUrl = "https://raw.githubusercontent.com/tabatkins/wordle-list/main/words";
const solutionsUrl =
  "https://raw.githubusercontent.com/3b1b/videos/master/_2022/wordle/data/possible_words.txt";

const tabRaw = await fetchText(tabatkinsUrl);
const validWords = [...new Set(parseFiveLetterWords(tabRaw))].sort();

const solRaw = await fetchText(solutionsUrl);
const solutionSet = new Set(parseFiveLetterWords(solRaw));

const answerWords = validWords.filter((w) => solutionSet.has(w));

if (answerWords.length < 1500) {
  console.warn(`ANSWER_WORDS count ${answerWords.length} is low; check sources.`);
}

const webPath = path.join(root, "artifacts/web-app/src/data/wordList.ts");
const apiPath = path.join(root, "artifacts/api-server/src/game/wordList.ts");

fs.mkdirSync(path.dirname(webPath), { recursive: true });
fs.writeFileSync(webPath, emitSetFile("VALID_WORDS", validWords), "utf8");
fs.writeFileSync(apiPath, emitApiWordList(validWords, answerWords), "utf8");

console.log(`Wrote ${validWords.length} VALID_WORDS -> ${path.relative(root, webPath)}`);
console.log(`Wrote VALID_WORDS + ${answerWords.length} ANSWER_WORDS -> ${path.relative(root, apiPath)}`);
